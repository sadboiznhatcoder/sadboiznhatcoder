-- BƯỚC 1: BẬT EXTENSION CẦN THIẾT
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ────────────────────────────────────────────────────────────
-- BƯỚC 2: TẠO HOẶC CẬP NHẬT BẢNG ORDERS (ĐƠN HÀNG & VIETQR)
-- ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS orders (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  order_code TEXT UNIQUE NOT NULL DEFAULT '',
  customer_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT NOT NULL,
  address TEXT NOT NULL,
  company_name TEXT,
  tax_code TEXT,
  total_amount NUMERIC NOT NULL,
  transfer_content TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  items JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Cập nhật cột nếu bảng orders đã tồn tại từ trước nhưng thiếu cột
ALTER TABLE orders ADD COLUMN IF NOT EXISTS order_code TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();

-- Tự động điền order_code nếu có bản ghi cũ chưa có mã đơn
UPDATE orders 
SET order_code = 'NAT-' || UPPER(SUBSTRING(id::text, 1, 6)) 
WHERE order_code IS NULL OR order_code = '';

-- Ràng buộc UNIQUE và NOT NULL cho order_code
DO $$
BEGIN
  ALTER TABLE orders ALTER COLUMN order_code SET NOT NULL;
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'orders_order_code_key'
  ) THEN
    ALTER TABLE orders ADD CONSTRAINT orders_order_code_key UNIQUE (order_code);
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

-- Check constraint cho status
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'orders_status_check'
  ) THEN
    ALTER TABLE orders ADD CONSTRAINT orders_status_check 
      CHECK (status IN ('pending', 'paid', 'shipped', 'completed', 'cancelled'));
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

-- Check constraint cho total_amount > 0
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'orders_total_amount_positive'
  ) THEN
    ALTER TABLE orders ADD CONSTRAINT orders_total_amount_positive 
      CHECK (total_amount > 0);
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

-- Tạo index cho bảng orders
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_phone ON orders(phone);
CREATE INDEX IF NOT EXISTS idx_orders_code ON orders(order_code);

-- ────────────────────────────────────────────────────────────
-- BƯỚC 3: TẠO HOẶC CẬP NHẬT BẢNG POSTS (BÀI VIẾT SEO)
-- ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS posts (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  title TEXT NOT NULL,
  slug TEXT NOT NULL,
  content TEXT NOT NULL DEFAULT '',
  meta_description TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT 'kien-thuc',
  image TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Cập nhật cột nếu bảng posts cũ thiếu
ALTER TABLE posts ADD COLUMN IF NOT EXISTS slug TEXT;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS meta_description TEXT DEFAULT '';
ALTER TABLE posts ADD COLUMN IF NOT EXISTS category TEXT DEFAULT 'kien-thuc';
ALTER TABLE posts ADD COLUMN IF NOT EXISTS image TEXT DEFAULT '';
ALTER TABLE posts ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();

-- Ràng buộc UNIQUE cho slug
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'posts_slug_key'
  ) THEN
    ALTER TABLE posts ADD CONSTRAINT posts_slug_key UNIQUE (slug);
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

-- Index cho posts
CREATE INDEX IF NOT EXISTS idx_posts_created_at ON posts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_posts_category ON posts(category);

-- ────────────────────────────────────────────────────────────
-- BƯỚC 4: TẠO HOẶC CẬP NHẬT BẢNG PRODUCTS (SẢN PHẨM & LINH KIỆN)
-- ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'mua-ban',
  description TEXT DEFAULT '',
  price TEXT NOT NULL DEFAULT '0',
  quantity INTEGER NOT NULL DEFAULT 1,
  images TEXT[] DEFAULT '{}',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE products ADD COLUMN IF NOT EXISTS category TEXT DEFAULT 'mua-ban';
ALTER TABLE products ADD COLUMN IF NOT EXISTS description TEXT DEFAULT '';
ALTER TABLE products ADD COLUMN IF NOT EXISTS price TEXT DEFAULT '0';
ALTER TABLE products ADD COLUMN IF NOT EXISTS quantity INTEGER DEFAULT 1;
ALTER TABLE products ADD COLUMN IF NOT EXISTS images TEXT[] DEFAULT '{}';
ALTER TABLE products ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT NOW();

CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_products_created_at ON products(created_at DESC);

-- ────────────────────────────────────────────────────────────
-- BƯỚC 5: TRIGGER TỰ ĐỘNG CẬP NHẬT UPDATED_AT CHO POSTS & ORDERS
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_posts_updated_at ON posts;
CREATE TRIGGER set_posts_updated_at
  BEFORE UPDATE ON posts
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS set_orders_updated_at ON orders;
CREATE TRIGGER set_orders_updated_at
  BEFORE UPDATE ON orders
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_updated_at();

-- ────────────────────────────────────────────────────────────
-- BƯỚC 6: XÓA TRIỆT ĐỂ TOÀN BỘ POLICIES CŨ (TRÁNH LỖI ERROR 42710)
-- ────────────────────────────────────────────────────────────
-- Đoạn mã PL/pgSQL này sẽ quét toàn bộ pg_policies và xóa sạch mọi policy
-- trên 3 bảng orders, posts, products bất kể trước đó đặt tên là gì.
DO $$ 
DECLARE
  pol RECORD;
BEGIN
  FOR pol IN 
    SELECT policyname, tablename 
    FROM pg_policies 
    WHERE schemaname = 'public' AND tablename IN ('orders', 'products', 'posts') 
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON %I', pol.policyname, pol.tablename);
  END LOOP;
END $$;

-- ────────────────────────────────────────────────────────────
-- BƯỚC 7: BẬT RLS VÀ THIẾT LẬP POLICIES CHUẨN MỚI
-- ────────────────────────────────────────────────────────────

-- 7a. BẢNG ORDERS (BẢO VỆ DỮ LIỆU KHÁCH HÀNG)
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

-- Khách hàng và Server API được phép đặt đơn mới
CREATE POLICY "orders_insert_policy" ON orders
  FOR INSERT
  WITH CHECK (true);

-- Chỉ Admin (authenticated) và Server Backend (service_role) mới được xem đơn hàng
CREATE POLICY "orders_select_policy" ON orders
  FOR SELECT
  TO authenticated, service_role
  USING (true);

-- Chỉ Admin và Server Backend mới được cập nhật trạng thái đơn (status)
CREATE POLICY "orders_update_policy" ON orders
  FOR UPDATE
  TO authenticated, service_role
  USING (true)
  WITH CHECK (true);


-- 7b. BẢNG POSTS (BÀI VIẾT)
ALTER TABLE posts ENABLE ROW LEVEL SECURITY;

-- Tất cả mọi người (khách hàng + Google bot) đều được đọc bài viết chuẩn SEO
CREATE POLICY "posts_select_policy" ON posts
  FOR SELECT
  USING (true);

-- Admin và hệ thống được thêm/sửa/xóa bài viết
CREATE POLICY "posts_write_policy" ON posts
  FOR ALL
  USING (true)
  WITH CHECK (true);


-- 7c. BẢNG PRODUCTS (SẢN PHẨM & LINH KIỆN)
ALTER TABLE products ENABLE ROW LEVEL SECURITY;

-- Tất cả mọi người đều xem được danh sách và chi tiết sản phẩm
CREATE POLICY "products_select_policy" ON products
  FOR SELECT
  USING (true);

-- Quản trị viên và hệ thống được thêm/sửa/xóa sản phẩm
CREATE POLICY "products_write_policy" ON products
  FOR ALL
  USING (true)
  WITH CHECK (true);

-- ────────────────────────────────────────────────────────────
-- BƯỚC 8: BUCKET STORAGE "images" (ẢNH SẢN PHẨM & BÀI VIẾT)
-- ────────────────────────────────────────────────────────────
INSERT INTO storage.buckets (id, name, public)
VALUES ('images', 'images', true)
ON CONFLICT (id) DO NOTHING;

DO $$
BEGIN
  DROP POLICY IF EXISTS "images_public_read" ON storage.objects;
  CREATE POLICY "images_public_read" ON storage.objects 
    FOR SELECT USING (bucket_id = 'images');

  DROP POLICY IF EXISTS "images_anon_insert" ON storage.objects;
  CREATE POLICY "images_anon_insert" ON storage.objects 
    FOR INSERT WITH CHECK (bucket_id = 'images');

  DROP POLICY IF EXISTS "images_anon_update" ON storage.objects;
  CREATE POLICY "images_anon_update" ON storage.objects 
    FOR UPDATE USING (bucket_id = 'images');

  DROP POLICY IF EXISTS "images_anon_delete" ON storage.objects;
  CREATE POLICY "images_anon_delete" ON storage.objects 
    FOR DELETE USING (bucket_id = 'images');
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

